"""Rebuild every figure and write review_pack/FIGURE_DATA.md from the same run.

    python tools/build_figure_data.py

FIGURE_DATA.md is what an outside reviewer reads instead of the code, so it
must come from the run that produced the PNGs, never be edited by hand.
"""
import importlib.util
import os
import sys
import textwrap

_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path[:] = [p for p in sys.path if os.path.abspath(p or os.getcwd()) != _HERE]
sys.path.insert(0, os.path.dirname(_HERE))

spec = importlib.util.spec_from_file_location("make_figures", os.path.join(_HERE, "make_figures.py"))
mf = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mf)

OUT = os.path.join(os.path.dirname(_HERE), "review_pack", "FIGURE_DATA.md")


def main():
    mf._setup_style()
    mf._assert_palette()
    ctx = mf.Ctx("data")
    parts = ["# Figure data — every value plotted, and every caption\n",
             "Generated by `python tools/build_figure_data.py` in the same run "
             "that writes the PNGs;\nevery number is computed at run time, so "
             "this file cannot disagree with the figures.\n"]
    for n in sorted(mf.FIGURES):
        out = mf.FIGURES[n](ctx) or {}
        cap = out.pop("CAPTION", None)
        parts.append(f"---\n\n## fig{n:02d}\n")
        if out:
            parts.append("| key | value |\n|---|---|")
            parts += [f"| `{k}` | {str(v).replace('|', '/')} |" for k, v in out.items()]
            parts.append("")
        if cap:
            parts.append("**Caption**\n")
            parts.append(textwrap.fill(cap, 92) + "\n")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(parts))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
